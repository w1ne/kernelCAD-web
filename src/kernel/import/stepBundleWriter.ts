// Turn an XCAF snapshot into a portable KernelCAD project. Geometry stays in
// native OCCT BREP files; the source script only names each occurrence and
// places/colors its independently transformable imported shape.

import { createHash } from 'node:crypto';
import { lstat, mkdir, mkdtemp, open, rm, writeFile } from 'node:fs/promises';
import { basename, dirname, join, resolve } from 'node:path';
import process from 'node:process';
import { decomposeStepTransform } from './stepAssemblyImport';
import type { StepAssemblySnapshot, StepImportOccurrence } from './stepAssemblyTypes';

export interface WriteStepBundleInput {
  inputName: string;
  inputBytes: Uint8Array;
  externalDocuments?: ReadonlyMap<string, Uint8Array>;
  outDir: string;
  assemblyName: string;
  snapshot: StepAssemblySnapshot;
}

export interface WrittenStepBundle {
  outDir: string;
  script: string;
  manifest: string;
  partAssets: number;
  occurrenceCount: number;
  definitionCount: number;
}

function sha256(bytes: Uint8Array): string {
  return createHash('sha256').update(bytes).digest('hex');
}

function scriptName(sourcePath: string[], index: number): string {
  const normalized = sourcePath
    .map((segment) => segment.normalize('NFKC').trim().replace(/[^\p{L}\p{N}_-]+/gu, '-').replace(/^-+|-+$/g, ''))
    .filter(Boolean)
    .join('__');
  return normalized || `part-${String(index).padStart(6, '0')}`;
}

function numberLiteral(value: number): string {
  if (!Number.isFinite(value)) throw new Error(`Cannot emit non-finite KernelCAD number: ${value}`);
  return Object.is(value, -0) ? '0' : JSON.stringify(value);
}

function emitScript(assemblyName: string, occurrences: StepImportOccurrence[], hashByDefinition: Map<string, string>): string {
  const lines = [
    '// Generated by `kernelcad import-step`; source hierarchy and units are in manifest.json.',
    '// STEP feature history, mates, and motion are not inferred by this static import.',
    `const imported = assembly(${JSON.stringify(assemblyName)});`,
  ];
  const usedNames = new Set<string>();
  occurrences.forEach((occurrence, index) => {
    const variable = `part_${String(index + 1).padStart(6, '0')}`;
    const baseName = scriptName(occurrence.sourcePath, index + 1);
    let name = baseName;
    let suffix = 1;
    while (usedNames.has(name)) name = `${baseName}__${String(index + 1).padStart(6, '0')}_${suffix++}`;
    usedNames.add(name);

    const assetHash = hashByDefinition.get(occurrence.definitionId);
    if (assetHash === undefined) throw new Error(`Missing BREP asset for definition '${occurrence.definitionId}'.`);
    const assetPath = `./parts/${assetHash}.brep`;
    const placement = decomposeStepTransform(occurrence.transform);

    lines.push(`const ${variable} = await lib.fromBREP(${JSON.stringify(assetPath)});`);
    if (placement.degrees !== 0) {
      lines.push(`${variable}.rotate([${placement.axis.map(numberLiteral).join(', ')}], ${numberLiteral(placement.degrees)});`);
    }
    if (placement.translate.some((value) => value !== 0)) {
      lines.push(`${variable}.translate(${placement.translate.map(numberLiteral).join(', ')});`);
    }
    if (occurrence.color !== undefined) lines.push(`${variable}.color(${JSON.stringify(occurrence.color.hex)});`);
    lines.push(`imported.part(${JSON.stringify(name)}, ${variable});`);
  });
  lines.push('return imported.model();', '');
  return lines.join('\n');
}

async function pathExists(path: string): Promise<boolean> {
  try {
    await lstat(path);
    return true;
  } catch (error) {
    if (typeof error === 'object' && error !== null && 'code' in error && (error as { code?: unknown }).code === 'ENOENT') return false;
    throw error;
  }
}

function errorCode(error: unknown): string | undefined {
  return typeof error === 'object' && error !== null && 'code' in error
    ? String((error as { code?: unknown }).code)
    : undefined;
}

function throwRenameError(destination: string, nativeCode: number, existsError: boolean): never {
  if (existsError) {
    const error = new Error(`Output path already exists: '${destination}'.`);
    Object.assign(error, { code: 'EEXIST' });
    throw error;
  }
  throw new Error(`Cannot atomically publish STEP bundle to '${destination}' (native error ${nativeCode}).`);
}

/** Rename a complete staged bundle into place with an OS-level no-replace guarantee. */
export async function renameDirectoryNoReplace(staging: string, outDir: string): Promise<void> {
  if (!['darwin', 'linux', 'win32'].includes(process.platform)) {
    throw new Error(`Atomic no-replace STEP bundle publication is unsupported on '${process.platform}'.`);
  }
  const koffi = (await import('koffi')).default;

  if (process.platform === 'darwin') {
    const libSystem = koffi.load(null);
    const renameExclusive = libSystem.func('int renamex_np(const char *from, const char *to, unsigned int flags)');
    if (renameExclusive(staging, outDir, 0x00000004) === 0) return; // RENAME_EXCL
    const nativeCode = koffi.errno();
    throwRenameError(outDir, nativeCode, nativeCode === koffi.os.errno.EEXIST || nativeCode === koffi.os.errno.ENOTEMPTY || nativeCode === koffi.os.errno.EISDIR);
  }

  if (process.platform === 'linux') {
    const libc = koffi.load(null);
    const renameNoReplace = libc.func('int renameat2(int oldDirFd, const char *oldPath, int newDirFd, const char *newPath, unsigned int flags)');
    if (renameNoReplace(-100, staging, -100, outDir, 0x00000001) === 0) return; // AT_FDCWD, RENAME_NOREPLACE
    const nativeCode = koffi.errno();
    throwRenameError(outDir, nativeCode, nativeCode === koffi.os.errno.EEXIST || nativeCode === koffi.os.errno.ENOTEMPTY || nativeCode === koffi.os.errno.EISDIR);
  }

  if (process.platform === 'win32') {
    const kernel32 = koffi.load('kernel32.dll');
    const moveFile = kernel32.func('int __stdcall MoveFileW(const wchar_t *from, const wchar_t *to)');
    const getLastError = kernel32.func('uint32_t __stdcall GetLastError(void)');
    if (moveFile(staging, outDir) !== 0) return;
    const nativeCode = getLastError();
    throwRenameError(outDir, nativeCode, nativeCode === 80 || nativeCode === 183);
  }

}

/** Publish the complete staging directory in one atomic no-replace operation. */
export async function publishStagedStepBundle(staging: string, outDir: string): Promise<void> {
  try {
    await renameDirectoryNoReplace(staging, outDir);
  } catch (error) {
    if (errorCode(error) === 'EEXIST') throw new Error(`Output path already exists: '${outDir}'.`);
    throw error;
  }
}

/** Build in a sibling staging directory, then claim and fill the destination without replacement. */
export async function writeStepBundle(input: WriteStepBundleInput): Promise<WrittenStepBundle> {
  const outDir = resolve(input.outDir);
  const parent = dirname(outDir);
  const base = basename(outDir);
  const lockPath = join(parent, `.${base}.kernelcad-import-step.lock`);
  await mkdir(parent, { recursive: true });

  let lock: Awaited<ReturnType<typeof open>> | undefined;
  try {
    lock = await open(lockPath, 'wx', 0o600);
  } catch (error) {
    if (typeof error === 'object' && error !== null && 'code' in error && (error as { code?: unknown }).code === 'EEXIST') {
      throw new Error(`Another STEP import is publishing to '${outDir}'.`);
    }
    throw error;
  }

  let staging: string | undefined;
  try {
    if (await pathExists(outDir)) throw new Error(`Output path already exists: '${outDir}'.`);
    staging = await mkdtemp(join(parent, `.${base}.staging-`));
    const partsDir = join(staging, 'parts');
    await mkdir(partsDir);

    const assetByHash = new Map<string, Uint8Array>();
    const hashByDefinition = new Map<string, string>();
    const manifestDefinitions: Array<Record<string, unknown>> = [];
    for (const definition of input.snapshot.definitions) {
      const hash = sha256(definition.brep);
      hashByDefinition.set(definition.id, hash);
      assetByHash.set(hash, definition.brep);
      manifestDefinitions.push({
        id: definition.id,
        sourceLabel: definition.sourceLabel,
        originalName: definition.name,
        asset: `parts/${hash}.brep`,
        sha256: hash,
        serializationVersion: definition.brepVersion,
        solidCount: definition.solidCount,
        boundsMm: definition.boundsMm,
        volumeMm3: definition.volumeMm3,
        validation: { valid: true, closedSolids: definition.solidCount },
      });
    }

    for (const [hash, bytes] of assetByHash) await writeFile(join(partsDir, `${hash}.brep`), bytes, { flag: 'wx' });

    const manifestOccurrences = input.snapshot.occurrences.map((occurrence) => {
      const placement = decomposeStepTransform(occurrence.transform);
      return {
        id: occurrence.id,
        originalName: occurrence.name,
        sourcePath: occurrence.sourcePath,
        definitionId: occurrence.definitionId,
        transformMm: {
          matrixColumnMajor: occurrence.transform,
          translation: placement.translate,
          rotationAxis: placement.axis,
          rotationDegrees: placement.degrees,
        },
        ...(occurrence.color !== undefined ? { color: occurrence.color } : {}),
      };
    });

    const scriptPath = `${input.assemblyName}.kcad.ts`;
    const script = emitScript(input.assemblyName, input.snapshot.occurrences, hashByDefinition);
    const manifest = {
      schemaVersion: 1,
      generatedBy: 'kernelcad import-step',
      input: {
        fileName: basename(input.inputName),
        sha256: sha256(input.inputBytes),
        sizeBytes: input.inputBytes.byteLength,
        dependencies: [...(input.externalDocuments ?? new Map()).entries()]
          .sort(([a], [b]) => a.localeCompare(b))
          .map(([fileName, bytes]) => ({ fileName, sha256: sha256(bytes), sizeBytes: bytes.byteLength })),
      },
      assemblyName: input.assemblyName,
      sourceLengthUnits: input.snapshot.sourceLengthUnits,
      canonicalLengthUnit: 'mm',
      definitions: manifestDefinitions,
      occurrences: manifestOccurrences,
      warnings: input.snapshot.warnings,
    };

    await writeFile(join(staging, scriptPath), script, { flag: 'wx' });
    await writeFile(join(staging, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`, { flag: 'wx' });
    if (await pathExists(outDir)) throw new Error(`Output path already exists: '${outDir}'.`);
    await publishStagedStepBundle(staging, outDir);
    return {
      outDir,
      script: join(outDir, scriptPath),
      manifest: join(outDir, 'manifest.json'),
      partAssets: assetByHash.size,
      occurrenceCount: input.snapshot.occurrences.length,
      definitionCount: input.snapshot.definitions.length,
    };
  } finally {
    if (staging !== undefined) await rm(staging, { recursive: true, force: true });
    await lock?.close();
    await rm(lockPath, { force: true });
  }
}

export function validateStepBundleName(name: string): string | undefined {
  if (name.trim() === '') return '--name must contain at least one non-whitespace character.';
  if (name.includes('/') || name.includes('\\') || name === '.' || name === '..') {
    return '--name must be a single assembly label, not a path.';
  }
  const hasControlCharacter = [...name].some((character) => {
    const code = character.codePointAt(0) ?? 0;
    return code <= 0x1f || (code >= 0x7f && code <= 0x9f);
  });
  if (hasControlCharacter) return '--name cannot contain control characters.';
  if (name.endsWith('.kcad.ts')) return '--name is the assembly label; omit the .kcad.ts suffix.';
  return undefined;
}
