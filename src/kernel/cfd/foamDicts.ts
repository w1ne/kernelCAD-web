// OpenFOAM case dictionaries for a steady incompressible simpleFoam run on
// a snappyHexMesh mesh. Pure string builders: `writeFoamCase(spec)` returns
// a map of case-relative path -> file text, so the dictionaries are unit
// tested without a solver.
//
// Mesh route: blockMesh background box -> snappyHexMesh against the STL
// kernelCAD exports (one STL region per named patch, so the inlet / outlet
// / wall patches carry the model's face names) -> checkMesh.

import { writeFieldFiles } from './foamFields';
import type { FoamCaseSpec, FoamPatch, Vec3 } from './types';

export const HEADER = (cls: string, object: string, location?: string): string =>
  [
    '/*--------------------------------*- C++ -*----------------------------------*\\',
    '  Generated by kernelCAD run_cfd. Edit the .kcad.ts study, not this file.',
    '\\*---------------------------------------------------------------------------*/',
    'FoamFile',
    '{',
    '    version     2.0;',
    '    format      ascii;',
    `    class       ${cls};`,
    ...(location !== undefined ? [`    location    "${location}";`] : []),
    `    object      ${object};`,
    '}',
    '',
  ].join('\n');

/** Round to 9 significant digits so dictionaries are byte-stable. */
export function num(v: number): string {
  if (v === 0) return '0';
  return String(Number(v.toPrecision(9)));
}

const vec = (v: Vec3): string => `(${v.map(num).join(' ')})`;

export const STL_NAME = 'geometry';

function blockMeshDict(spec: FoamCaseSpec): string {
  const [x0, y0, z0] = spec.block.min;
  const [x1, y1, z1] = spec.block.max;
  const verts: Vec3[] = [
    [x0, y0, z0], [x1, y0, z0], [x1, y1, z0], [x0, y1, z0],
    [x0, y0, z1], [x1, y0, z1], [x1, y1, z1], [x0, y1, z1],
  ];
  const faces = ['(0 4 7 3)', '(1 2 6 5)', '(0 1 5 4)', '(3 7 6 2)', '(0 3 2 1)', '(4 5 6 7)'];
  // Group the six box faces by patch name (external sides share 'sides').
  const byName = new Map<string, { patch: FoamPatch; faces: string[] }>();
  spec.blockPatches.forEach((p, i) => {
    const g = byName.get(p.name) ?? { patch: p, faces: [] };
    g.faces.push(faces[i]);
    byName.set(p.name, g);
  });
  const boundary = [...byName.values()].map(({ patch, faces: fs }) =>
    `    ${patch.name}\n    {\n        type ${patch.role === 'wall' ? 'wall' : 'patch'};\n        faces\n        (\n${fs.map(f => `            ${f}`).join('\n')}\n        );\n    }`,
  );
  return HEADER('dictionary', 'blockMeshDict', 'system') + [
    'scale 1;',
    '',
    'vertices',
    '(',
    ...verts.map(v => `    ${vec(v)}`),
    ');',
    '',
    'blocks',
    '(',
    `    hex (0 1 2 3 4 5 6 7) (${spec.block.cells.join(' ')}) simpleGrading (1 1 1)`,
    ');',
    '',
    'boundary',
    '(',
    boundary.join('\n'),
    ');',
    '',
  ].join('\n');
}

function surfaceFeatureExtractDict(): string {
  return HEADER('dictionary', 'surfaceFeatureExtractDict', 'system') + [
    `${STL_NAME}.stl`,
    '{',
    '    extractionMethod    extractFromSurface;',
    '    includedAngle       150;',
    '    subsetFeatures { nonManifoldEdges no; openEdges yes; }',
    '    writeObj            no;',
    '}',
    '',
  ].join('\n');
}

function snappyHexMeshDict(spec: FoamCaseSpec): string {
  const L = spec.surfaceLevel;
  const regionsGeom = spec.stlPatches.map(p => `            ${p.name} { name ${p.name}; }`).join('\n');
  const regionsRefine = spec.stlPatches
    .map(p => `            ${p.name} { level (${L} ${L}); patchInfo { type ${p.role === 'wall' ? 'wall' : 'patch'}; } }`)
    .join('\n');
  const box = spec.refineBox;
  return HEADER('dictionary', 'snappyHexMeshDict', 'system') + [
    'castellatedMesh true;',
    'snap            true;',
    'addLayers       false;',
    '',
    'geometry',
    '{',
    `    ${STL_NAME}.stl`,
    '    {',
    '        type triSurfaceMesh;',
    `        name ${STL_NAME};`,
    '        regions',
    '        {',
    regionsGeom,
    '        }',
    '    }',
    ...(box !== undefined ? [`    refineBox { type searchableBox; min ${vec(box.min)}; max ${vec(box.max)}; }`] : []),
    '}',
    '',
    'castellatedMeshControls',
    '{',
    '    maxLocalCells       2000000;',
    '    maxGlobalCells      4000000;',
    '    minRefinementCells  0;',
    '    maxLoadUnbalance    0.10;',
    '    nCellsBetweenLevels 3;',
    `    features ( { file "${STL_NAME}.eMesh"; level ${L}; } );`,
    '    refinementSurfaces',
    '    {',
    `        ${STL_NAME}`,
    '        {',
    `            level (${L} ${L});`,
    '            regions',
    '            {',
    regionsRefine,
    '            }',
    '        }',
    '    }',
    '    resolveFeatureAngle 30;',
    '    refinementRegions',
    '    {',
    ...(box !== undefined ? [`        refineBox { mode inside; levels ((1e15 ${box.level})); }`] : []),
    '    }',
    `    locationInMesh ${vec(spec.locationInMesh)};`,
    '    allowFreeStandingZoneFaces true;',
    '}',
    '',
    'snapControls',
    '{',
    '    nSmoothPatch    3;',
    '    tolerance       2.0;',
    '    nSolveIter      100;',
    '    nRelaxIter      5;',
    '    nFeatureSnapIter 10;',
    '    implicitFeatureSnap false;',
    '    explicitFeatureSnap true;',
    '    multiRegionFeatureSnap true;',
    '}',
    '',
    'addLayersControls',
    '{',
    '    relativeSizes true;',
    '    layers { }',
    '    expansionRatio 1.0;',
    '    finalLayerThickness 0.3;',
    '    minThickness 0.1;',
    '    nGrow 0;',
    '    featureAngle 60;',
    '    nRelaxIter 3;',
    '    nSmoothSurfaceNormals 1;',
    '    nSmoothNormals 3;',
    '    nSmoothThickness 10;',
    '    maxFaceThicknessRatio 0.5;',
    '    maxThicknessToMedialRatio 0.3;',
    '    minMedialAxisAngle 90;',
    '    nBufferCellsNoExtrude 0;',
    '    nLayerIter 50;',
    '}',
    '',
    'meshQualityControls',
    '{',
    '    #includeEtc "caseDicts/meshQualityDict"',
    '    nSmoothScale 4;',
    '    errorReduction 0.75;',
    '}',
    '',
    'mergeTolerance 1e-6;',
    '',
  ].join('\n');
}

/** Patch names by role, in declaration order. */
export function patchesOf(spec: FoamCaseSpec, role: FoamPatch['role']): string[] {
  const all = [...spec.blockPatches, ...spec.stlPatches];
  return [...new Set(all.filter(p => p.role === role).map(p => p.name))];
}

function patchFunctions(spec: FoamCaseSpec): string[] {
  const out: string[] = [];
  for (const patch of [...patchesOf(spec, 'inlet'), ...patchesOf(spec, 'outlet')]) {
    for (const [suffix, op, field] of [['flow', 'sum', 'phi'], ['p', 'areaAverage', 'p']] as const) {
      out.push(
        `    ${patch}_${suffix}`,
        '    {',
        '        type surfaceFieldValue; libs (fieldFunctionObjects);',
        '        writeControl timeStep; writeInterval 1; log false; writeFields false;',
        `        regionType patch; name ${patch}; operation ${op}; fields (${field});`,
        '    }',
      );
    }
  }
  return out;
}

function controlDict(spec: FoamCaseSpec): string {
  const f = spec.forces;
  const fns = [
    ...patchFunctions(spec),
    '    maxU',
    '    {',
    '        type fieldMinMax; libs (fieldFunctionObjects);',
    '        writeControl timeStep; writeInterval 1; log false;',
    '        mode magnitude; location false; fields (U);',
    '    }',
    ...(f !== undefined
      ? [
          '    bodyForces',
          '    {',
          '        type forces; libs (forces);',
          '        writeControl timeStep; writeInterval 1; log false;',
          `        patches (${f.patch}); rho rhoInf; rhoInf ${num(f.rhoInf)}; CofR ${vec(f.CofR)};`,
          '    }',
        ]
      : []),
    '    midPlane',
    '    {',
    '        type surfaces; libs (sampling);',
    '        writeControl onEnd;',
    '        surfaceFormat vtk;',
    '        formatOptions { vtk { format ascii; legacy true; } }',
    '        fields (U p);',
    '        interpolate false;',
    '        surfaces',
    '        {',
    '            plane',
    '            {',
    '                type cuttingPlane; planeType pointAndNormal;',
    `                pointAndNormalDict { point ${vec(spec.plane.point)}; normal ${vec(spec.plane.normal)}; }`,
    '                interpolate false;',
    '            }',
    '        }',
    '    }',
  ];
  return HEADER('dictionary', 'controlDict', 'system') + [
    'application     simpleFoam;',
    'startFrom       startTime;',
    'startTime       0;',
    'stopAt          endTime;',
    `endTime         ${spec.iterations};`,
    'deltaT          1;',
    'writeControl    timeStep;',
    `writeInterval   ${spec.iterations};`,
    'purgeWrite      1;',
    'writeFormat     ascii;',
    'writePrecision  8;',
    'writeCompression off;',
    'timeFormat      general;',
    'timePrecision   6;',
    'runTimeModifiable false;',
    '',
    'functions',
    '{',
    ...fns,
    '}',
    '',
  ].join('\n');
}

function fvSchemes(spec: FoamCaseSpec): string {
  const turb = spec.turbulence === 'kOmegaSST'
    ? ['    div(phi,k)      bounded Gauss upwind;', '    div(phi,omega)  bounded Gauss upwind;']
    : [];
  return HEADER('dictionary', 'fvSchemes', 'system') + [
    'ddtSchemes { default steadyState; }',
    'gradSchemes { default cellLimited Gauss linear 1; }',
    'divSchemes',
    '{',
    '    default         none;',
    // Laminar: second-order linearUpwind (validated against Hagen-Poiseuille).
    // RANS: the TVD limitedLinearV, which keeps steady SIMPLE from cycling on
    // snapped meshes around jets and corners.
    spec.turbulence === 'kOmegaSST'
      ? '    div(phi,U)      bounded Gauss limitedLinearV 1;'
      : '    div(phi,U)      bounded Gauss linearUpwind grad(U);',
    ...turb,
    '    div((nuEff*dev2(T(grad(U))))) Gauss linear;',
    '}',
    'laplacianSchemes { default Gauss linear limited corrected 0.5; }',
    'interpolationSchemes { default linear; }',
    'snGradSchemes { default limited corrected 0.5; }',
    'wallDist { method meshWave; }',
    '',
  ].join('\n');
}

function fvSolution(spec: FoamCaseSpec): string {
  const r = num(spec.residualTarget);
  const turbFields = spec.turbulence === 'kOmegaSST' ? '|k|omega' : '';
  return HEADER('dictionary', 'fvSolution', 'system') + [
    'solvers',
    '{',
    '    p { solver GAMG; smoother GaussSeidel; tolerance 1e-8; relTol 0.05; }',
    `    "(U${turbFields})" { solver smoothSolver; smoother symGaussSeidel; tolerance 1e-9; relTol 0.1; }`,
    '}',
    '',
    'SIMPLE',
    '{',
    '    nNonOrthogonalCorrectors 1;',
    '    consistent      yes;',
    '    residualControl',
    '    {',
    `        p ${r};`,
    `        U ${r};`,
    ...(spec.turbulence === 'kOmegaSST' ? [`        "(k|omega)" ${r};`] : []),
    '    }',
    '}',
    '',
    'relaxationFactors',
    '{',
    '    equations { U 0.9; ".*" 0.7; }',
    '}',
    '',
  ].join('\n');
}

function transportProperties(spec: FoamCaseSpec): string {
  return HEADER('dictionary', 'transportProperties', 'constant') +
    `transportModel  Newtonian;\nnu              ${num(spec.fluid.nu)};\n`;
}

function turbulenceProperties(spec: FoamCaseSpec): string {
  const body = spec.turbulence === 'laminar'
    ? 'simulationType laminar;\n'
    : 'simulationType RAS;\nRAS\n{\n    RASModel kOmegaSST;\n    turbulence on;\n    printCoeffs off;\n}\n';
  return HEADER('dictionary', 'turbulenceProperties', 'constant') + body;
}

function decomposeParDict(spec: FoamCaseSpec): string {
  return HEADER('dictionary', 'decomposeParDict', 'system') +
    `numberOfSubdomains ${spec.cores};\nmethod scotch;\n`;
}

/** Every file of the case, case-relative path -> text. The STL is written
 *  separately (it is geometry, not a dictionary). */
export function writeFoamCase(spec: FoamCaseSpec): Record<string, string> {
  return {
    'system/blockMeshDict': blockMeshDict(spec),
    'system/surfaceFeatureExtractDict': surfaceFeatureExtractDict(),
    'system/snappyHexMeshDict': snappyHexMeshDict(spec),
    'system/controlDict': controlDict(spec),
    'system/fvSchemes': fvSchemes(spec),
    'system/fvSolution': fvSolution(spec),
    'system/decomposeParDict': decomposeParDict(spec),
    'constant/transportProperties': transportProperties(spec),
    'constant/turbulenceProperties': turbulenceProperties(spec),
    ...writeFieldFiles(spec, HEADER),
  };
}
