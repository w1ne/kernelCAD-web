// Pure builder for the order pack: the BOM (CSV + JSON), per-part model /
// drawing files, vendor paste texts, a machine-readable manifest and a human
// README, laid out as zip entries. Nothing here touches the filesystem or the
// agent layer: the caller computes the CSV, collects the file bytes and names
// the zip. fflate keeps the module browser-safe.

import { strToU8, zipSync } from 'fflate';
import { buildHandoffs } from './handoffs';
import type { OrderPackBomRow } from './orderRows';

export interface OrderPackFileInput {
  row: OrderPackBomRow;
  kind: 'step' | 'stl' | 'dxf' | 'drawing';
  bytes: Uint8Array;
}

export interface OrderPackEntry {
  path: string;
  bytes: Uint8Array;
}

export interface OrderPack {
  name: string;
  entries: OrderPackEntry[];
}

export interface OrderPackTotals {
  partCount: number;
  uniquePartCount: number;
  totalMassG: number | null;
}

const MODEL_BASENAME: Record<Exclude<OrderPackFileInput['kind'], 'drawing'>, string> = {
  step: 'model.step',
  stl: 'model.stl',
  dxf: 'model.dxf',
};

/** McMaster interprets a quantity as packs, and no pack-size data exists in
 *  the catalog yet (see handoffs.ts), so this caveat travels with the pack. */
const MCMASTER_CAVEAT =
  'Quantities mean packs at McMaster — verify pack size before ordering. Include one line per part number only.';

/** `${item}-${slug(name)}`: lowercase, [^a-z0-9]+ → '-', trim '-', fallback 'part'. */
export function partFolderName(row: OrderPackBomRow): string {
  const slug = row.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
  return `${row.item}-${slug === '' ? 'part' : slug}`;
}

function entryPath(folder: string, kind: OrderPackFileInput['kind']): string {
  return `parts/${folder}/${kind === 'drawing' ? 'drawing.pdf' : MODEL_BASENAME[kind]}`;
}

function packReadme(name: string, notes: readonly string[]): string {
  return [
    `Order pack: ${name}`,
    '',
    'What this is: the bill of materials and the per-part files needed to',
    'quote and order this design, plus paste-ready lists for the vendor',
    'order pages.',
    '',
    'File kinds:',
    '  bom.csv, bom.json    the bill of materials (bom.json carries the totals)',
    '  parts/<item>-<name>/ one folder per part:',
    '    model.step         CAD model for machining and fabrication quotes',
    '    model.stl          triangle mesh for 3D printing',
    '    model.dxf          flat pattern for sheet cutting',
    '    drawing.pdf        dimensioned drawing for quote upload pages',
    '  handoffs/*.txt       paste-ready part lists for the vendor order pages',
    '  manifest.json        machine-readable index of this pack',
    '',
    'Paste lists: the handoffs texts are for the vendors\' own public order',
    'pages. kernelCAD sends nothing to any vendor — nothing was sent; open',
    'the page and paste the list yourself.',
    '',
    'McMaster: ' + MCMASTER_CAVEAT,
    '',
    ...(notes.length > 0 ? ['Notes:', ...notes.map((n) => `  ${n}`), ''] : []),
    'Generated by kernelCAD.',
    '',
  ].join('\n');
}

export function buildOrderPack(args: {
  name: string;
  rows: readonly OrderPackBomRow[];
  totals?: OrderPackTotals | null;
  csv: string;
  files: readonly OrderPackFileInput[];
  notes?: readonly string[];
}): OrderPack {
  const totals = args.totals ?? null;
  const notes = [...(args.notes ?? [])];

  const partFiles = new Map<number, string[]>();
  const fileEntries: OrderPackEntry[] = [];
  for (const f of args.files) {
    const path = entryPath(partFolderName(f.row), f.kind);
    fileEntries.push({ path, bytes: f.bytes });
    const list = partFiles.get(f.row.item);
    if (list === undefined) partFiles.set(f.row.item, [path]);
    else list.push(path);
  }

  const manifest =
    JSON.stringify(
      {
        name: args.name,
        created: new Date().toISOString(),
        parts: args.rows.map((row) => ({
          folder: partFolderName(row),
          name: row.name,
          qty: row.quantity,
          kind: row.kind,
          process: row.process,
          material: row.material,
          massG: row.massGTotal,
          files: partFiles.get(row.item) ?? [],
        })),
        handoffCaveats: { mcmaster: MCMASTER_CAVEAT },
        notes,
      },
      null,
      2,
    ) + '\n';
  const bom = JSON.stringify({ rows: args.rows, totals }, null, 2) + '\n';

  const entries: OrderPackEntry[] = [
    { path: 'manifest.json', bytes: strToU8(manifest) },
    { path: 'README.txt', bytes: strToU8(packReadme(args.name, notes)) },
    { path: 'bom.csv', bytes: strToU8(args.csv) },
    { path: 'bom.json', bytes: strToU8(bom) },
  ];
  const handoffs = buildHandoffs(args.rows);
  if (handoffs.mcmaster !== null) entries.push({ path: 'handoffs/mcmaster.txt', bytes: strToU8(handoffs.mcmaster) });
  if (handoffs.mouser !== null) entries.push({ path: 'handoffs/mouser.txt', bytes: strToU8(handoffs.mouser) });
  if (handoffs.digikey !== null) entries.push({ path: 'handoffs/digikey.txt', bytes: strToU8(handoffs.digikey) });
  entries.push(...fileEntries);

  return { name: args.name, entries };
}

export function zipEntries(entries: readonly OrderPackEntry[]): Uint8Array {
  const files: Record<string, Uint8Array> = {};
  for (const e of entries) files[e.path] = e.bytes;
  return zipSync(files);
}

/** The caller names the zip file itself; entry paths already carry the pack
 *  name via the manifest and README, so `name` changes nothing here. */
export function zipOrderPack(pack: OrderPack, name: string): Uint8Array {
  void name;
  return zipEntries(pack.entries);
}
