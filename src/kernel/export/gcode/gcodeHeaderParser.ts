/** Predictions and generator identity reported by the retained G-code comments.
 * Header identity is provenance from the artifact, not executable attestation. */
export interface GcodeStats {
  slicer?: { name: 'OrcaSlicer' | 'PrusaSlicer'; version: string };
  estimatedPrintTimeSeconds?: number;
  filamentUsedGrams?: number;
  filamentUsedMeters?: number;
  layerCount?: number;
  maxZMm?: number;
}

function nonnegative(text: string): number | undefined {
  if (!/^(?:\d+(?:\.\d*)?|\.\d+)$/.test(text.trim())) return undefined;
  const value = Number(text);
  return Number.isFinite(value) && value >= 0 ? value : undefined;
}

function sumSlots(text: string | undefined): number | undefined {
  if (text === undefined) return undefined;
  const slots = text.split(',').map(nonnegative);
  if (slots.some(value => value === undefined)) return undefined;
  const total = (slots as number[]).reduce((sum, value) => sum + value, 0);
  return Number.isFinite(total) ? total : undefined;
}

/** Whole-value duration, including upstream days and fractional short seconds. */
function parseDuration(text: string | undefined): number | undefined {
  if (text === undefined) return undefined;
  const match = /^(?:(\d+)\s*d\s*)?(?:(\d+)\s*h\s*)?(?:(\d+)\s*m\s*)?(?:(\d+(?:\.\d+)?)\s*s\s*)?$/.exec(text.trim());
  if (!match || !match.slice(1).some(value => value !== undefined)) return undefined;
  const seconds = Number(match[1] ?? 0) * 86400 + Number(match[2] ?? 0) * 3600
    + Number(match[3] ?? 0) * 60 + Number(match[4] ?? 0);
  return Number.isFinite(seconds) ? seconds : undefined;
}

function parseSlicerIdentity(comments: readonly string[]): GcodeStats['slicer'] {
  for (const line of comments) {
    const generated = /^generated by (OrcaSlicer|PrusaSlicer) ([\w.+-]+)(?: on .*)?$/i.exec(line);
    if (generated) {
      return { name: generated[1].toLowerCase() === 'orcaslicer' ? 'OrcaSlicer' : 'PrusaSlicer', version: generated[2] };
    }
  }
  return undefined;
}

/** Missing or malformed metadata is omitted; executable/config lines are ignored. */
export function parseGcodeHeader(gcode: string): GcodeStats {
  const stats: GcodeStats = {};
  const comments = gcode.split(/\r?\n/).flatMap(line => {
    const match = /^\s*;\s*(.*?)\s*$/.exec(line);
    return match ? [match[1]] : [];
  });
  const value = (pattern: RegExp): string | undefined => {
    for (const line of comments) {
      const match = pattern.exec(line);
      if (match) return match[1].trim();
    }
    return undefined;
  };
  const slicer = parseSlicerIdentity(comments);
  if (slicer !== undefined) stats.slicer = slicer;
  const time = parseDuration(value(/^estimated printing time \(normal mode\)\s*=\s*(.*)$/i))
    ?? parseDuration(value(/^estimated printing time\s*=\s*(.*)$/i))
    ?? parseDuration(value(/^model printing time:.*;\s*total estimated time:\s*(.*)$/i));
  if (time !== undefined) stats.estimatedPrintTimeSeconds = time;
  const totalMass = value(/^total filament used \[g\]\s*=\s*(.*)$/i);
  const grams = totalMass === undefined
    ? sumSlots(value(/^filament used \[g\]\s*=\s*(.*)$/i)) : nonnegative(totalMass);
  if (grams !== undefined) stats.filamentUsedGrams = grams;
  const mm = sumSlots(value(/^filament used \[mm\]\s*=\s*(.*)$/i));
  if (mm !== undefined) stats.filamentUsedMeters = mm / 1000;
  const rawLayers = value(/^total layers count\s*=\s*(.*)$/i) ?? value(/^total layer number:\s*(.*)$/i);
  const layers = rawLayers === undefined ? undefined : nonnegative(rawLayers);
  if (layers !== undefined && Number.isSafeInteger(layers)) stats.layerCount = layers;
  const rawZ = value(/^max_z_height:\s*(.*)$/i);
  const maxZ = rawZ === undefined ? undefined : nonnegative(rawZ);
  if (maxZ !== undefined) stats.maxZMm = maxZ;
  return stats;
}
