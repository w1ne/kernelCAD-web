// Emit a self-contained three.js ES module for one catalog asset. The module
// embeds the low-poly GLB's node tree and flat (non-indexed) triangle
// positions, and builds a THREE.Group synchronously:
//
//   import createAsset, { params, presets, palette, meta } from './pine-tree.mjs';
//   scene.add(createAsset({ leaves: '#c9772b' }));
//
// Colour knobs recolour their palette zone at runtime (no server, no bake).
// Knobs that change geometry need a baked variant: `createAsset` throws for
// those with a message naming get_variant + export, rather than silently
// returning the default shape.

import { NodeIO, type Node as GltfNode } from '@gltf-transform/core';
import type { CatalogAsset } from '../../shared/assets/catalogSchema';

export interface AssetModuleOptions {
  /** Import specifier for three.js (default `'three'`, resolved by a bundler or import map). */
  readonly threeSpecifier?: string;
}

interface EmittedNode {
  name: string;
  matrix: number[];
  mesh?: { position: string; zone: number } | { position: string; color: string; opacity: number };
  children: EmittedNode[];
}

function base64Floats(values: Float32Array): string {
  return Buffer.from(values.buffer, values.byteOffset, values.byteLength).toString('base64');
}

function srgbHex(linear: ArrayLike<number>): string {
  const toSrgb = (c: number) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);
  return `#${[0, 1, 2].map((k) => Math.round(Math.min(1, Math.max(0, toSrgb(linear[k]!))) * 255).toString(16).padStart(2, '0')).join('')}`;
}

function emitNode(node: GltfNode, zoneOf: (hex: string) => number): EmittedNode {
  const out: EmittedNode = {
    name: node.getName(),
    matrix: Array.from(node.getMatrix(), (v) => Math.round(v * 1e9) / 1e9),
    children: node.listChildren().map((child) => emitNode(child, zoneOf)),
  };
  const prim = node.getMesh()?.listPrimitives()[0];
  const position = prim?.getAttribute('POSITION');
  if (prim !== undefined && position != null) {
    const array = position.getArray();
    if (!(array instanceof Float32Array)) throw new Error(`asset module: node '${out.name}' POSITION is not float32.`);
    const material = prim.getMaterial();
    const color = prim.getAttribute('COLOR_0');
    // Opaque parts share the palette material and carry their zone colour in
    // COLOR_0; glass/translucent parts keep their own material.
    const onPalette = material?.getName() === 'kernelcad-palette' && color !== null;
    const zone = onPalette ? zoneOf(srgbHex(color.getElement(0, []))) : -1;
    out.mesh = zone >= 0
      ? { position: base64Floats(array), zone }
      : {
        position: base64Floats(array),
        color: srgbHex(material?.getBaseColorFactor() ?? [0.8, 0.8, 0.8, 1]),
        opacity: material?.getAlpha() ?? 1,
      };
  }
  return out;
}

/** The module source for `asset`, from its low-poly GLB at default knobs. */
export async function emitAssetModule(
  asset: CatalogAsset,
  glb: Uint8Array,
  options: AssetModuleOptions = {},
): Promise<string> {
  const doc = await new NodeIO().readBinary(glb);
  const zones = asset.palette.map((zone) => ({ color: zone.color, ...(zone.param === undefined ? {} : { param: zone.param }), name: zone.name }));
  const zoneOf = (hex: string) => zones.findIndex((zone) => zone.color === hex);
  const roots = doc.getRoot().listScenes()[0]?.listChildren() ?? [];
  const nodes = roots.map((root) => emitNode(root, zoneOf));
  const colorKnobs = asset.params.filter((p) => p.type === 'color').map((p) => p.name);
  const meta = {
    id: asset.id,
    title: asset.title,
    kit: asset.kit,
    category: asset.category,
    origin: asset.origin,
    sizeM: asset.stats.sizeM,
    triangles: asset.stats.triangles,
    license: asset.license,
    source: asset.source,
  };
  const json = (value: unknown) => JSON.stringify(value);
  return `// Generated by kernelCAD from ${asset.source} — do not edit; edit the .kcad.ts source.
// Original kernelCAD geometry, licence ${asset.license}. Low-poly, metres, Y up.
import * as THREE from ${json(options.threeSpecifier ?? 'three')};

export const meta = ${json(meta)};
export const params = ${json(asset.params)};
export const presets = ${json(asset.presets)};
export const palette = ${json(zones)};
export const rig = ${json(asset.rig ?? {})};
/** Knobs createAsset applies at runtime (colour zones); the rest change geometry. */
export const runtimeKnobs = ${json(colorKnobs)};

const NODES = ${json(nodes)};

function floats(b64) {
  const bytes = Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
  return new Float32Array(bytes.buffer);
}

function resolveKnobs(options) {
  const { preset, ...overrides } = options ?? {};
  const fromPreset = preset === undefined ? {} : presets[preset];
  if (fromPreset === undefined) throw new Error(\`\${meta.id}: unknown preset '\${preset}'. Presets: \${Object.keys(presets).join(', ') || 'none'}.\`);
  const knobs = { ...fromPreset, ...overrides };
  for (const [name, value] of Object.entries(knobs)) {
    const param = params.find((p) => p.name === name);
    if (param === undefined) throw new Error(\`\${meta.id}: unknown knob '\${name}'. Knobs: \${params.map((p) => p.name).join(', ')}.\`);
    if (param.type !== 'color' && value !== param.default) {
      throw new Error(\`\${meta.id}: knob '\${name}' changes geometry; bake that variant (MCP get_variant, then export with style 'lowpoly') and load its GLB.\`);
    }
  }
  return knobs;
}

/** Build the asset as a THREE.Group. Colour knobs (and presets) recolour palette zones. */
export function createAsset(options = {}) {
  const knobs = resolveKnobs(options);
  const shared = new THREE.MeshStandardMaterial({ roughness: 1, metalness: 0, flatShading: true });
  shared.name = 'kernelcad-palette';
  const zoneColors = palette.map((zone) => new THREE.Color(zone.param !== undefined && knobs[zone.param] !== undefined ? knobs[zone.param] : zone.color));
  const build = (spec) => {
    const object = spec.mesh === undefined ? new THREE.Group() : (() => {
      const geometry = new THREE.BufferGeometry();
      geometry.setAttribute('position', new THREE.BufferAttribute(floats(spec.mesh.position), 3));
      geometry.computeVertexNormals();
      if (spec.mesh.zone !== undefined) {
        const count = geometry.getAttribute('position').count;
        const colors = new Float32Array(count * 3);
        const c = zoneColors[spec.mesh.zone];
        for (let i = 0; i < count; i++) { colors[i * 3] = c.r; colors[i * 3 + 1] = c.g; colors[i * 3 + 2] = c.b; }
        geometry.setAttribute('color', new THREE.BufferAttribute(colors, 3));
        if (!shared.vertexColors) shared.vertexColors = true;
        return new THREE.Mesh(geometry, shared);
      }
      const own = new THREE.MeshStandardMaterial({ color: spec.mesh.color, roughness: 0.1, metalness: 0, transparent: spec.mesh.opacity < 1, opacity: spec.mesh.opacity < 1 ? spec.mesh.opacity : 0.45, flatShading: true });
      return new THREE.Mesh(geometry, own);
    })();
    object.name = spec.name;
    object.matrix.fromArray(spec.matrix);
    object.matrix.decompose(object.position, object.quaternion, object.scale);
    for (const child of spec.children) object.add(build(child));
    return object;
  };
  const group = new THREE.Group();
  group.name = meta.id;
  for (const node of NODES) group.add(build(node));
  group.userData.kernelcad = { id: meta.id, knobs };
  return group;
}

export default createAsset;
`;
}
