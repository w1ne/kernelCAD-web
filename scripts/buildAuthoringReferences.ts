// Embeds src/agent/skills/kernelcad-authoring/references/*.md into
// src/agent/skills/authoringReferences.gen.ts so `lookup_authoring_skill`
// serves every reference section from any host.
//
// Why a generated module: kernelCAD-server bundles src/agent/mcp/toolRegistry.ts
// with esbuild (no markdown loader) and passes only the lean SKILL.md text to
// lookupAuthoringSkill(). Bundling the references as strings keeps section
// lookup complete without changing the server.
//
//   npx tsx scripts/buildAuthoringReferences.ts           # write
//   npx tsx scripts/buildAuthoringReferences.ts --check   # exit 1 when stale
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

export const REFERENCES_DIR = 'src/agent/skills/kernelcad-authoring/references';
export const GENERATED_PATH = 'src/agent/skills/authoringReferences.gen.ts';

/** Reading order of the reference files; unknown files follow alphabetically. */
const ORDER = ['workflow.md', 'api.md', 'verification.md', 'cli.md', 'recipes.md', 'materials.md', 'cookbook-index.md'];

export interface ReferenceFile {
  file: string;
  markdown: string;
}

export function readReferenceFiles(dir: string = REFERENCES_DIR): ReferenceFile[] {
  const names = readdirSync(dir).filter((n) => n.endsWith('.md'));
  const rank = (n: string) => (ORDER.includes(n) ? ORDER.indexOf(n) : ORDER.length);
  names.sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));
  return names.map((n) => ({ file: `references/${n}`, markdown: readFileSync(join(dir, n), 'utf8') }));
}

export function renderReferencesModule(refs: readonly ReferenceFile[]): string {
  const body = refs
    .map((r) => `  {\n    file: ${JSON.stringify(r.file)},\n    markdown: ${JSON.stringify(r.markdown)},\n  },`)
    .join('\n');
  return [
    '// SPDX-License-Identifier: MIT',
    '// Copyright (c) 2026 Andrii Shylenko and kernelCAD contributors',
    '//',
    '// GENERATED by scripts/buildAuthoringReferences.ts from',
    `// ${REFERENCES_DIR}/*.md — do not edit; edit the markdown and re-run.`,
    '',
    'export interface AuthoringReference {',
    '  /** Path relative to the kernelcad-authoring skill dir. */',
    '  file: string;',
    '  markdown: string;',
    '}',
    '',
    'export const AUTHORING_REFERENCES: readonly AuthoringReference[] = [',
    body,
    '];',
    '',
  ].join('\n');
}

function main(): void {
  const check = process.argv.includes('--check');
  const next = renderReferencesModule(readReferenceFiles());
  const prev = existsSync(GENERATED_PATH) ? readFileSync(GENERATED_PATH, 'utf8') : '';
  if (prev === next) {
    console.log(`✓ ${GENERATED_PATH} is up to date`);
    return;
  }
  if (check) {
    console.error(`✗ ${GENERATED_PATH} is stale — run \`npm run skill:references\``);
    process.exit(1);
  }
  writeFileSync(GENERATED_PATH, next);
  console.log(`✓ wrote ${GENERATED_PATH}`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
