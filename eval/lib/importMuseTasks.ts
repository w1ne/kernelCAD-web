// Importer for MUSE benchmark cases (arXiv:2605.28579, dataset
// huggingface.co/datasets/dongxiaoyu/MUSE, CC BY 4.0).
//
// For each requested case it renders:
//   eval/tasks/muse-<case>/prompt.md   — the MUSE design specification,
//                                        retargeted from "emit CadQuery"
//                                        to "emit a kernelCAD .kcad.ts"
//   eval/tasks/muse-<case>/harness.ts  — gates (clean evaluate) + scored
//                                        fields delegated to the MUSE
//                                        benchmark's own scoring stages
//                                        via eval/oracle/museScorer.ts
//
// The retargeting mirrors the MUSE candidate-generation rules (multiple
// independent components when the spec asks for them; preserve component
// count, proportions, and assembly intent) without adding engineering
// hints beyond the language-target change — same adaptation contract as
// the cqe-task* importer.
//
// Usage:
//   npx tsx eval/lib/importMuseTasks.ts --dataset ~/projects/muse/data/muse/cases \
//       --cases stool chair table ...
//
// Idempotent: re-run to refresh prompts after a dataset update.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const TASKS_DIR = resolve('eval/tasks');

function promptFor(caseName: string, designDescription: string): string {
  return `# ${caseName} (imported from the MUSE text-to-CAD benchmark)

Build the following design as a kernelCAD \`.kcad.ts\` script. Millimetres, Z-up, degrees.

If the specification calls for multiple independent components, return a
multi-part model — one solid per named component — and preserve the
component count, proportions, and assembly intent from the specification.

## Design Specification

${designDescription.trim()}
`;
}

function harnessFor(caseName: string): string {
  return `// eval/tasks/muse-${caseName}/harness.ts
//
// Auto-generated by eval/lib/importMuseTasks.ts from the MUSE benchmark
// case '${caseName}' (dataset: huggingface.co/datasets/dongxiaoyu/MUSE).
//
// Gates (kernelCAD product gates, always on):
//   - evaluates clean (no blocking diagnostics)
//
// Scored fields (MUSE's own funnel stages, run by MUSE's code via
// eval/oracle/museScorer.ts — no thresholds of ours):
//   - 'muse stage1: sandbox executes'
//   - 'muse stage2: component overlap-free'
//
// The OCCT-validity stage (watertight / manifold / self-intersection)
// requires MUSE's external 'validator' module, which is not published;
// its availability and raw output are surfaced via metrics.

import { evaluateScript } from '../../oracle/kernelcad-client';
import { runMuseScorer } from '../../oracle/museScorer';
import type { HarnessCtx, HarnessResult } from '../../types';

export default async function harness(scriptPath: string, ctx?: HarnessCtx): Promise<HarnessResult> {
  const ev = await evaluateScript(scriptPath);
  if (!ev.ok) {
    return { gates: { 'evaluates clean': false }, scored: {} };
  }

  let sandboxOk = false;
  let overlapFree = false;
  let metrics: Record<string, number | boolean | string | null> | undefined;
  if (ctx) {
    try {
      const result = await runMuseScorer(scriptPath, ctx.runDir, 'muse-${caseName}');
      sandboxOk = result.sandboxOk;
      // Per MUSE funnel semantics a stage not reached counts as failed.
      overlapFree = result.overlapFree === true;
      metrics = {
        muse_reason: result.reason,
        muse_sandbox_ok: result.sandboxOk,
        muse_sandbox_error: result.sandboxError.slice(0, 500),
        muse_step_exists: result.stepExists,
        muse_solid_count: result.resultSolidCount,
        muse_bbox: result.bbox.join(','),
        muse_validator_available: result.validatorAvailable,
        muse_geometry_valid: result.geometry ? (result.geometry.geometry_valid as boolean) : null,
        muse_geometry_note: result.geometryNote,
        muse_overlap_free: result.overlapFree,
        muse_max_overlap_ratio: result.interpenetration?.max_overlap_ratio ?? null,
        muse_interpenetrating_pairs: result.interpenetration?.interpenetrating_pairs ?? null,
        muse_render_ok: result.renderOk,
        muse_render_png: result.renderPngPath,
        muse_render_step: result.renderStepPath,
        muse_export_ms: result.exportMs,
        muse_score_ms: result.scoreMs,
        muse_errors: result.errors.join(' | ').slice(0, 1000) || null,
      };
    } catch (err) {
      metrics = {
        muse_sandbox_ok: false,
        muse_reason: \`scorer threw: \${err instanceof Error ? err.message : String(err)}\`,
      };
    }
  }

  return {
    gates: { 'evaluates clean': true },
    scored: {
      'muse stage1: sandbox executes': sandboxOk,
      'muse stage2: component overlap-free': overlapFree,
    },
    ...(metrics !== undefined ? { metrics } : {}),
  };
}
`;
}

function main(): void {
  const args = process.argv.slice(2);
  let dataset = '';
  const cases: string[] = [];
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--dataset') {
      dataset = args[++i] ?? '';
    } else if (args[i] === '--cases') {
      while (i + 1 < args.length && !args[i + 1].startsWith('--')) {
        cases.push(args[++i]);
      }
    }
  }
  if (!dataset || cases.length === 0) {
    console.error('usage: npx tsx eval/lib/importMuseTasks.ts --dataset <muse cases dir> --cases <name> [name...]');
    process.exit(1);
  }

  for (const caseName of cases) {
    const srcDir = join(dataset, caseName);
    const descPath = join(srcDir, 'design_description.md');
    if (!existsSync(descPath)) {
      console.error(`SKIP ${caseName}: no design_description.md under ${srcDir}`);
      continue;
    }
    const description = readFileSync(descPath, 'utf8');
    const taskDir = join(TASKS_DIR, `muse-${caseName}`);
    mkdirSync(taskDir, { recursive: true });
    writeFileSync(join(taskDir, 'prompt.md'), promptFor(caseName, description));
    writeFileSync(join(taskDir, 'harness.ts'), harnessFor(caseName));
    console.error(`imported muse-${caseName}`);
  }
}

main();
