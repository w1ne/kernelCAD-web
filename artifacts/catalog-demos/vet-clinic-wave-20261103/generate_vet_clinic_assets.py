def js(value):
    return json.dumps(value, ensure_ascii=False)


def emit(asset_row):
    model = asset_row["id"]
    title = asset_row["title"]
    desc = asset_row["description"]
    tags = ["veterinary", "animal clinic", "animal health"] + title.lower().split() + ["low poly", "CC0"]
    lines = [
        f"// Original low-poly veterinary clinic scene asset. Millimetres, Z up, {asset_row['origin']} origin.",
        "meta({",
        f"  name: {js(model)},",
        "  license: 'CC0-1.0',",
        f"  title: {js(title)},",
        f"  description: {js(desc)} + ' Editable overall scale and asset color.',",
        f"  tags: {js(list(dict.fromkeys(tags)))},",
        "  kit: 'vet-clinic',",
        "  category: 'prop',",
        f"  origin: {js(asset_row['origin'])},",
        "  compat: ['veterinary', 'animal-clinic', 'animal-health', 'clinic', 'indoor'],",
        "  triangleBudget: 1800,",
        "});",
        "",
        "const scale = param('scale', 1, { label: 'Overall scale', min: 0.65, max: 1.35, step: 0.05 });",
        f"const color = param('color', {js(asset_row['color'])}, {{ label: 'Asset color' }});",
        f"const p = assembly({js(model)});",
        "",
        "const b = (name: string, size: [number, number, number], at: [number, number, number], rotation?: [number, number, number]) => {",
        "  let shape = box(size[0], size[1], size[2], true);",
        "  if (rotation?.[0]) shape = shape.rotate([1, 0, 0], rotation[0]);",
        "  if (rotation?.[1]) shape = shape.rotate([0, 1, 0], rotation[1]);",
        "  if (rotation?.[2]) shape = shape.rotate([0, 0, 1], rotation[2]);",
        "  p.part(name, shape.translate(at[0], at[1], at[2]).scale(scale).color(color));",
        "};",
    ]
    if any(part[0] == "cylinder" for part in asset_row["parts"]):
        lines.extend([
            "const c = (name: string, h: number, r: number, segments: number, at: [number, number, number], axis?: [number, number, number], degrees = 0) => {",
            "  let shape = cylinder(h, r, segments);",
            "  if (axis && degrees) shape = shape.rotate(axis, degrees);",
            "  p.part(name, shape.translate(at[0], at[1], at[2]).scale(scale).color(color));",
            "};",
        ])
    lines.append("")
    for part in asset_row["parts"]:
        kind = part[0]
        if kind == "box":
            _, name, size, at, rotation = part
            at = [at[0], at[1], at[2] + asset_row["floor_offset_mm"]]
            call = f"b({js(name)}, {js(size)}, {js(at)}"
            if rotation:
                call += f", {js(rotation)}"
            lines.append(call + ");")
        elif kind == "cylinder":
            _, name, dimensions, at, axis, degrees = part
            h, r, segments = dimensions
            at = [at[0], at[1], at[2] + asset_row["floor_offset_mm"]]
            call = f"c({js(name)}, {h}, {r}, {segments}, {js(at)}"
            if axis:
                call += f", {js(axis)}, {degrees}"
            lines.append(call + ");")
        else:
            raise ValueError(f"unsupported part kind: {kind}")
    lines.extend(["", "return p.model();", ""])
    return "\n".join(lines)


def main():
    KIT.mkdir(parents=True, exist_ok=True)
    kit = {
        "title": "Veterinary clinic",
        "description": "Original low-poly props for small-animal clinic reception, exam, treatment, imaging, surgery, diagnostics, inpatient housing, and grooming scenes.",
    }
    (KIT / "kit.json").write_text(json.dumps(kit, indent=2) + "\n", encoding="utf-8")
    for row in ASSETS:
        (KIT / f"{row['id']}.kcad.ts").write_text(emit(row), encoding="utf-8")
    print(f"wrote {len(ASSETS)} original veterinary clinic assets to {KIT}")


