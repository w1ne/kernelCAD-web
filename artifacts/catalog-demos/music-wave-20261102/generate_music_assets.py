def emit(asset):
    slug, title, description, color, parts = asset
    meta = {
        'name': slug,
        'license': 'CC0-1.0',
        'title': title,
        'description': description,
        'tags': [title.lower(), 'music', 'instrument', 'orchestra', 'low poly', 'CC0'],
        'kit': 'music',
        'category': 'prop',
        'origin': 'base',
        'compat': ['music', 'orchestra', 'stage', 'indoor'],
        'triangleBudget': 1800,
    }
    lines = [
        'meta(' + json.dumps(meta, ensure_ascii=False, indent=2) + ');',
        '',
        "const scale = param('scale', 1, { label: 'Overall scale', min: 0.65, max: 1.35, step: 0.05 });",
        "const color = param('color', " + json.dumps(color) + ", { label: 'Asset color' });",
        "const p = assembly(" + json.dumps(slug) + ");",
    ]
    for name, geometry in parts:
        lines.append(f"p.part({json.dumps(name)}, {geometry}.scale(scale).color(color));")
    lines.extend(['', 'return p.model();', ''])
    (KIT / f'{slug}.kcad.ts').write_text('\n'.join(lines), encoding='utf-8')


def main():
    if len(ASSETS) != 40:
        raise SystemExit(f'expected 40 assets, found {len(ASSETS)}')
    KIT.mkdir(parents=True, exist_ok=True)
    for item in ASSETS:
        emit(item)
    (KIT / 'kit.json').write_text(json.dumps({
        'title': 'Music instruments',
        'description': 'Original low-poly string, wind, percussion and stage props with editable size and color controls.'
    }, indent=2) + '\n', encoding='utf-8')
    print(f'generated {len(ASSETS)} music assets in {KIT}')


if __name__ == '__main__':
    main()
